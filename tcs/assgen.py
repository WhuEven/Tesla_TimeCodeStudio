"""监控风格 OSD 时间码的字幕（ASS）生成。

为什么用 ASS 而不是 drawtext：
  * 字体、描边、阴影、右下角定位都由 libass 精确渲染，跨平台一致；
  * 拼接后是一条连续的全局时间轴，一次叠加即可，不必为每个输入文件
    单独计算 drawtext 的起始偏移；
  * ``fontsdir`` 可以直接加载内置点阵字体，不要求安装到系统。

时间码按"每个片段文件名里的时间戳"生成 —— 片段之间若有约 1 秒的录制
缝隙，OSD 会如实地跳 1 秒，这正是真实录像的语义。
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path

from .model import RenderSegment


# ------------------------------------------------------------------ 样式配置

@dataclass
class OSSStyle:
    enabled: bool = True
    font_name: str = "TC OSD Dot"
    font_size: int = 0              # 0 = 按 height * size_ratio 自动
    size_ratio: float = 0.040
    primary: str = "#FFFFFF"
    outline_color: str = "#000000"
    outline: float = 2.4
    shadow: float = 1.6
    shadow_color: str = "#00000099"
    spacing: int = 2
    box: bool = False               # 半透明底板（BorderStyle=3）
    box_color: str = "#0000008C"
    margin_r_ratio: float = 0.028
    margin_v_ratio: float = 0.032
    time_format: str = "%Y-%m-%d %H:%M:%S"
    location: str = ""              # 副行文本，如 "杭州 丹枫路"

    def resolved_size(self, height: int) -> int:
        return self.font_size or max(12, int(round(height * self.size_ratio)))


# ------------------------------------------------------------------ 工具函数

def _ass_color(value: str, fallback_alpha: int = 0) -> str:
    """``#RRGGBB`` / ``#RRGGBBAA`` -> ASS ``&HAABBGGRR``。"""
    s = (value or "").strip().lstrip("#")
    if len(s) == 8:
        r, g, b, a = s[0:2], s[2:4], s[4:6], s[6:8]
        alpha = 255 - int(a, 16)
    elif len(s) == 6:
        r, g, b = s[0:2], s[2:4], s[4:6]
        alpha = fallback_alpha
    else:
        return "&H00FFFFFF"
    return f"&H{alpha:02X}{b}{g}{r}".upper()


def _ts(seconds: float) -> str:
    """秒 -> ``h:mm:ss.cc``（ASS 时间格式）。"""
    seconds = max(0.0, seconds)
    total_cs = int(round(seconds * 100))
    h, rem = divmod(total_cs, 360000)
    m, rem = divmod(rem, 6000)
    s, cs = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _escape(text: str) -> str:
    return text.replace("\\", "＼").replace("{", "｛").replace("}", "｝")


# ------------------------------------------------------------------ 生成主体

def build_ass(segments: list[RenderSegment], width: int, height: int,
              style: OSSStyle, out_path: str | Path,
              fps: float = 30.0) -> Path:
    """生成 ASS 字幕文件。"""
    out_path = Path(out_path)
    font_size = style.resolved_size(height)
    margin_r = max(2, int(round(width * style.margin_r_ratio)))
    margin_v = max(2, int(round(height * style.margin_v_ratio)))

    if style.box:
        border_style = 3
        outline_w = max(1.0, style.outline * 1.6)
        outline_c = _ass_color(style.box_color)
        back_c = _ass_color(style.box_color, 0x80)
    else:
        border_style = 1
        outline_w = style.outline
        outline_c = _ass_color(style.outline_color)
        back_c = _ass_color(style.shadow_color, 0x80)

    lines = [
        "[Script Info]",
        "; Generated by TimeCode Studio",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "Collisions: none",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
        "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, "
        "ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, "
        "MarginL, MarginR, MarginV, Encoding",
        (
            f"Style: OSD,{style.font_name},{font_size},"
            f"{_ass_color(style.primary)},&H00FFFFFF,{outline_c},{back_c},"
            f"0,0,0,0,100,100,{style.spacing},0,{border_style},"
            f"{outline_w:.1f},{style.shadow:.1f},3,{margin_r},{margin_r},{margin_v},1"
        ),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]

    loc = _escape(style.location.strip()) if style.location.strip() else ""

    for seg in segments:
        if seg.duration <= 0.0005:
            continue
        t = 0.0
        guard = 0
        while t < seg.duration - 0.0005 and guard < 400000:
            guard += 1
            local = seg.src_in + t
            whole = math.floor(local)
            # 到下一个整秒的剩余时长（保证 OSD 在整秒处跳变）
            step = min(whole + 1 - local, seg.duration - t)
            if step <= 0.0005:
                step = seg.duration - t
            stamp = (seg.start_dt + timedelta(seconds=whole)).strftime(style.time_format)
            text = _escape(stamp)
            if loc:
                text = f"{loc}\\N{text}"
            lines.append(
                f"Dialogue: 0,{_ts(seg.offset + t)},{_ts(seg.offset + t + step)},"
                f"OSD,,0,0,0,,{text}"
            )
            t += step

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path
