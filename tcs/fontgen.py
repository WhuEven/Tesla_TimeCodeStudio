"""生成监控 / 行车记录仪专用的点阵 OSD 字体。

真实 DVR、CCTV、TeslaCam 回放界面上的时间码几乎都是 5×7 或 6×8 点阵
字形。系统里通常没有这类字体，而在线下载的 Dot Matrix / DSEG 字体又涉及
授权问题，所以这里直接把 5×7 的点阵矩阵编译成一个矢量 TTF：

    每个点阵像素 -> 一个 100×100 单位的矩形轮廓

矢量化的好处是任意分辨率下都锐利，并且能被 libass（ffmpeg 的 ass 滤镜）
通过 ``fontsdir`` 直接加载，不要求用户安装到系统字体库。
"""

from __future__ import annotations

from pathlib import Path

FAMILY = "TC OSD Dot"
STYLE = "Regular"
POSTSCRIPT = "TCOSDDot-Regular"

UPM = 1000          # 每 em 单位数
PX = 100            # 单个点阵像素的边长（单位）
COLS, ROWS = 5, 7   # 点阵尺寸

# 5 列 × 7 行点阵，'1' 表示点亮
GLYPHS: dict[str, list[str]] = {
    "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
    "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "3": ["11111", "00010", "00100", "00010", "00001", "10001", "01110"],
    "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
    "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
    "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    "-": ["00000", "00000", "00000", "11111", "00000", "00000", "00000"],
    ":": ["00000", "00100", "00100", "00000", "00100", "00100", "00000"],
    ".": ["00000", "00000", "00000", "00000", "00000", "01100", "01100"],
    "/": ["00001", "00010", "00010", "00100", "01000", "01000", "10000"],
    "+": ["00000", "00100", "00100", "11111", "00100", "00100", "00000"],
    " ": ["00000", "00000", "00000", "00000", "00000", "00000", "00000"],
}

# 窄字符：冒号与句点只占半格，时间码看起来更像真实 OSD
NARROW = {":", ".", "/"}


def _rect(pen, x0: float, y0: float, x1: float, y1: float) -> None:
    pen.moveTo((x0, y0))
    pen.lineTo((x1, y0))
    pen.lineTo((x1, y1))
    pen.lineTo((x0, y1))
    pen.closePath()


def _build_glyph(rows: list[str], pen) -> None:
    for r, line in enumerate(rows):
        y_top = (ROWS - r) * PX
        y_bot = (ROWS - r - 1) * PX
        for c, cell in enumerate(line):
            if cell == "1":
                x0 = c * PX
                _rect(pen, x0, y_bot, x0 + PX, y_top)


def build_font(out_path: str | Path) -> Path:
    """编译并保存 TTF，返回文件路径。"""
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    glyph_order = [".notdef"]
    glyf: dict = {}
    metrics: dict = {}

    pen = TTGlyphPen(None)
    _rect(pen, 0, 0, COLS * PX, ROWS * PX)
    glyf[".notdef"] = pen.glyph()
    metrics[".notdef"] = (COLS * PX + PX, 0)

    cmap: dict[int, str] = {}
    for ch, rows in GLYPHS.items():
        name = "uni%04X" % ord(ch) if ch != " " else "space"
        glyph_order.append(name)
        pen = TTGlyphPen(None)
        _build_glyph(rows, pen)
        glyf[name] = pen.glyph()
        adv = (len(rows[0]) * PX + (PX // 2 if ch in NARROW else PX))
        metrics[name] = (adv, 0)
        cmap[ord(ch)] = name

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyf)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=750, descent=-250, lineGap=0)
    fb.setupNameTable(
        {
            "familyName": FAMILY,
            "styleName": STYLE,
            "uniqueFontIdentifier": f"{FAMILY}:{STYLE}",
            "fullName": f"{FAMILY} {STYLE}",
            "psName": POSTSCRIPT,
            "version": "Version 1.000",
            "copyright": "Generated by TimeCode Studio (public domain dot-matrix design).",
        }
    )
    fb.setupOS2(
        sTypoAscender=750,
        sTypoDescender=-250,
        sTypoLineGap=0,
        usWinAscent=750,
        usWinDescent=250,
        fsType=0,  # 可自由嵌入
    )
    fb.setupPost()
    fb.save(str(out_path))
    return out_path


def ensure_font(font_dir: str | Path) -> Path:
    """确保字体文件存在（缺失或损坏时重新生成）。"""
    font_dir = Path(font_dir)
    target = font_dir / f"{POSTSCRIPT}.ttf"
    if target.exists() and target.stat().st_size > 500:
        return target
    return build_font(target)


if __name__ == "__main__":
    import sys

    dest = sys.argv[1] if len(sys.argv) > 1 else "./assets/fonts"
    print(build_font(Path(dest) / f"{POSTSCRIPT}.ttf"))
