#!/bin/bash
# TimeCode Studio —— 生成 macOS 应用程序包
#
# 双击 .command 文件必然由「终端」打开，无法避免黑窗口；
# 本脚本把启动器封装成标准 .app，双击后直接出现图形界面，不弹终端。
#
# 用法：  ./build_app.sh
# 产物：  ./TimeCode Studio.app   （双击即可运行）
# 排错：  运行日志在项目根目录 launch.log
#
# 说明：主可执行文件优先编译成原生 Mach-O 启动器（arm64 + x86_64）。
# 若只用 shell 脚本作主可执行文件，LaunchServices 无法判断架构，
# 在 Apple Silicon 上会误判为 Intel 应用并索要 Rosetta。

set -e
cd "$(dirname "$0")" || exit 1
ROOT="$(pwd)"

APP="$ROOT/TimeCode Studio.app"
CONTENTS="$APP/Contents"

rm -rf "$APP"
mkdir -p "$CONTENTS/MacOS" "$CONTENTS/Resources"

# ---------------- 启动器脚本 ----------------
# 注意：弹窗文本一律使用 ASCII 英文。
# osascript 从 shell 接收 UTF-8 中文时，在部分系统区域设置下会显示成乱码。
{
    echo '#!/bin/bash'
    echo '# 项目根目录：由 build_app.sh 生成时写入（.app 被移动后请重新运行 build_app.sh）'
    echo "ROOT=\"$ROOT\""
    cat <<'SH'
# TimeCode Studio launcher (generated by build_app.sh)
# No terminal window: all output goes to a log file; errors raise a dialog.

DIR="$ROOT"
[ -d "$DIR" ] || DIR="$(cd "$(dirname "$0")/../../.." && pwd)"   # 兜底：从 Contents/MacOS 上溯三级
if [ ! -f "$DIR/main.py" ]; then
    osascript -e "display alert \"TimeCode Studio\" message \"main.py not found under: $DIR\" buttons {\"OK\"} default button 1" >/dev/null 2>&1
    exit 1
fi
cd "$DIR" || exit 1

# 日志：优先项目目录，不可写则回退到临时目录（只读介质 / 沙箱环境）
LOG="$DIR/launch.log"
if ! : > "$LOG" 2>/dev/null; then
    LOG="${TMPDIR:-/tmp}/TimeCodeStudio-launch.log"
    : > "$LOG" 2>/dev/null || LOG=/dev/null
fi
echo "[$(date '+%Y-%m-%d %H:%M:%S')] launch TimeCode Studio" >> "$LOG"
echo "root: $DIR" >> "$LOG"

alert() {  # alert "title" "message"
    [ -n "$TCS_NO_ALERT" ] && return 0   # 自动化测试时可关闭弹窗
    [ "$LOG" = "/dev/null" ] || open -e "$LOG" >/dev/null 2>&1
    osascript -e "display alert \"$1\" message \"$2\" buttons {\"OK\"} default button 1" >/dev/null 2>&1 || true
}

# 1) 选解释器：优先项目内虚拟环境
PY="$DIR/.venv/bin/python"
[ -x "$PY" ] || PY="$(command -v python3 || true)"
if [ -z "$PY" ]; then
    alert "Python not found" "Please install Python 3.9+ and run build_app.sh again."
    exit 1
fi
echo "python: $PY" >> "$LOG"

# 2) 依赖自检
if ! "$PY" -c "import PySide6, fontTools, imageio_ffmpeg" >>"$LOG" 2>&1; then
    echo "installing dependencies..." >> "$LOG"
    if ! "$PY" -m pip install -r "$DIR/requirements.txt" >>"$LOG" 2>&1; then
        alert "Dependency install failed" "Run manually: $PY -m pip install -r requirements.txt"
        exit 1
    fi
fi

# 3) 启动图形界面
if [ -n "$TCS_DRYRUN" ]; then      # 自检用：只验证解释器与路径，不真正开窗口
    echo "dry-run: would start $PY $DIR/main.py" >> "$LOG"
    exit 0
fi
"$PY" "$DIR/main.py" >>"$LOG" 2>&1
code=$?
if [ $code -ne 0 ]; then
    echo "exit code $code" >> "$LOG"
    alert "TimeCode Studio quit unexpectedly" "Exit code $code. See launch.log for details."
fi
SH
} > "$CONTENTS/MacOS/launcher"
chmod +x "$CONTENTS/MacOS/launcher"

# ---------------- 原生启动器（规避 Rosetta 误判） ----------------
EXEC_NAME="launcher"
BIN="$CONTENTS/MacOS/TimeCodeStudio"
if command -v clang >/dev/null 2>&1; then
    STUB_SRC="$CONTENTS/MacOS/__stub.c"
    cat > "$STUB_SRC" <<'C'
/* 原生启动器：exec 同目录下的 launcher 脚本。
   存在的意义是让 .app 拥有真正的 Mach-O 可执行文件，架构可被系统识别，
   否则纯脚本 bundle 在 Apple Silicon 上会被要求安装 Rosetta。 */
#include <mach-o/dyld.h>
#include <libgen.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>
#include <limits.h>

int main(void) {
    char exe[PATH_MAX];
    uint32_t size = sizeof(exe);
    if (_NSGetExecutablePath(exe, &size) != 0) return 1;

    char dirbuf[PATH_MAX];
    strncpy(dirbuf, exe, sizeof(dirbuf) - 1);
    dirbuf[sizeof(dirbuf) - 1] = '\0';
    const char *dir = dirname(dirbuf);

    char script[PATH_MAX];
    int n = snprintf(script, sizeof(script), "%s/launcher", dir);
    if (n <= 0 || n >= (int)sizeof(script)) return 1;

    execl("/bin/bash", "bash", script, (char *)NULL);
    return 1;
}
C
    if clang -O2 -arch arm64 -arch x86_64 -o "$BIN" "$STUB_SRC" 2>/dev/null \
       || clang -O2 -arch arm64 -o "$BIN" "$STUB_SRC" 2>/dev/null; then
        EXEC_NAME="TimeCodeStudio"
        chmod +x "$BIN"
    fi
    rm -f "$STUB_SRC"
fi

# ---------------- Info.plist ----------------
cat > "$CONTENTS/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>TimeCode Studio</string>
    <key>CFBundleDisplayName</key>
    <string>TimeCode Studio</string>
    <key>CFBundleIdentifier</key>
    <string>com.whueven.timecodestudio</string>
    <key>CFBundleVersion</key>
    <string>1.0</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0</string>
    <key>CFBundleExecutable</key>
    <string>${EXEC_NAME}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>LSArchitecturePriority</key>
    <array>
        <string>arm64</string>
        <string>x86_64</string>
    </array>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.video</string>
</dict>
</plist>
PLIST

# ---------------- 图标：png -> iconset -> icns ----------------
if [ -f "$ROOT/assets/AppIcon.png" ] && command -v iconutil >/dev/null 2>&1; then
    ICONSET="$(mktemp -d)/AppIcon.iconset"
    mkdir -p "$ICONSET"
    for spec in "16:16" "16:32" "32:32" "32:64" "128:128" "128:256" "256:256" "256:512" "512:512" "512:1024"; do
        px="${spec%%:*}"; out="${spec##*:}"
        sips -z "$out" "$out" "$ROOT/assets/AppIcon.png" --out "$ICONSET/icon_${px}x${px}.png" >/dev/null 2>&1
        [ "$px" != "$out" ] && mv "$ICONSET/icon_${px}x${px}.png" "$ICONSET/icon_${px}x${px}@2x.png" 2>/dev/null
    done
    iconutil -c icns "$ICONSET" -o "$CONTENTS/Resources/AppIcon.icns" >/dev/null 2>&1 || true
    rm -rf "$(dirname "$ICONSET")"
fi

# 去掉隔离属性，避免首次双击被 Gatekeeper 拦下
xattr -cr "$APP" 2>/dev/null || true

# 刷新 LaunchServices 缓存，避免沿用旧的"需要 Rosetta"判定
LSREGISTER="/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"
[ -x "$LSREGISTER" ] && "$LSREGISTER" -f "$APP" >/dev/null 2>&1 || true

echo "已生成：$APP"
echo "主可执行文件：Contents/MacOS/$EXEC_NAME"
[ "$EXEC_NAME" = "TimeCodeStudio" ] \
    && echo "（原生 $(lipo -archs "$BIN" 2>/dev/null) 启动器）" \
    || echo "（警告：未找到 clang，回退为脚本启动器，可能仍会被要求安装 Rosetta）"
echo "双击即可运行（不弹终端）。日志：$ROOT/launch.log"
